-- 删除用量日汇总表
--
-- usage_daily 自建立起就只有写入方、没有任何读取方：maintenance 每小时把已结束的
-- 日期汇总进去，而管理页的图表、接口全部直接读 usage_logs。等于每天白写一次，
-- 只换来一个没人看的副本。
--
-- 它原本的设计意图是「保留期把明细删掉之后，长期统计仍有据可依」。但页面的区间
-- 选择器最大 90 天、保留期是 30 天，中间那 60 天本来就没有数据可看——汇总表能补的
-- 只是这个没人提的需求。与其维持一条空的写入路径，不如去掉：
-- 长期统计的需求改由管理页「数据维护」手动触发清理来覆盖，见 admin.ts 的
-- POST /maintenance/prune。
--
-- 表里当前没有数据，DROP 不丢任何东西（本迁移之前它始终是 0 行）。

DROP TABLE IF EXISTS usage_daily;
